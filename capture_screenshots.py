"""
Captures the 15 NoteShareHub screenshots for the report.

Before running:
  1. Start Apache + MySQL in XAMPP and install the database via
     http://localhost/NoteSharing/setup.php
  2. pip install playwright
     python -m playwright install chromium
  3. python capture_screenshots.py
     (change BASE below if your folder is not NoteSharing)

Images are saved in the folder  screenshots/  as 3.1.png ... 3.15.png
"""
import os
from playwright.sync_api import sync_playwright

BASE = "http://localhost/NoteSharing"
STUDENT = (
    os.environ.get("NOTESHARE_STUDENT_EMAIL", "rahul.cse@notesharing.edu"),
    os.environ.get("NOTESHARE_STUDENT_PASSWORD", ""),
)
ADMIN = (
    os.environ.get("NOTESHARE_ADMIN_EMAIL", "admin@notesharing.edu"),
    os.environ.get("NOTESHARE_ADMIN_PASSWORD", ""),
)
OUT = "screenshots"
os.makedirs(OUT, exist_ok=True)

if not STUDENT[1] or not ADMIN[1]:
    raise RuntimeError(
        "Set NOTESHARE_STUDENT_PASSWORD and NOTESHARE_ADMIN_PASSWORD "
        "to the passwords generated by setup.php before capturing screenshots."
    )

def shot(page, url, name, full=False):
    page.goto(BASE + url, wait_until="networkidle")
    page.wait_for_timeout(1200)          # let charts / fonts finish
    page.screenshot(path=f"{OUT}/{name}.png", full_page=full)
    print("saved", name, url)

def login(browser, creds):
    ctx = browser.new_context(viewport={"width": 1366, "height": 800})
    page = ctx.new_page()
    page.goto(BASE + "/login.php", wait_until="networkidle")
    page.fill("#email", creds[0])
    page.fill("#password", creds[1])
    page.click("button[type=submit]")
    page.wait_for_load_state("networkidle")
    return ctx, page

with sync_playwright() as p:
    browser = p.chromium.launch()

    # --- public pages (not logged in)
    ctx = browser.new_context(viewport={"width": 1366, "height": 800})
    pg = ctx.new_page()
    shot(pg, "/index.php", "3.1")
    shot(pg, "/register.php", "3.2", full=True)
    shot(pg, "/login.php", "3.3")
    ctx.close()

    # --- student pages
    ctx, pg = login(browser, STUDENT)
    shot(pg, "/dashboard.php", "3.4", full=True)
    shot(pg, "/explore.php?q=database&dept=1", "3.5", full=True)
    shot(pg, "/note-details.php?id=1", "3.6", full=True)
    shot(pg, "/upload-note.php", "3.7", full=True)
    shot(pg, "/my-uploads.php", "3.8", full=True)
    shot(pg, "/bookmarks.php", "3.9", full=True)
    ctx.close()

    # --- admin pages
    ctx, pg = login(browser, ADMIN)
    shot(pg, "/admin/dashboard.php", "3.10", full=True)
    shot(pg, "/admin/users.php", "3.11", full=True)
    shot(pg, "/admin/notes.php", "3.12", full=True)
    shot(pg, "/admin/subjects.php", "3.13", full=True)
    shot(pg, "/admin/departments.php", "3.14", full=True)
    shot(pg, "/admin/reports.php", "3.15", full=True)
    ctx.close()
    browser.close()
print("Done. Upload the images in the 'screenshots' folder.")